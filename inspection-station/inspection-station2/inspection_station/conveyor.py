class PyMotors:
    """Python port (lgpio pulse thread). Used when the team C program can't be built."""
    TICK = 0.02

    def __init__(self, settings, log, sim=False):
        self.s = settings
        self.log = log
        self.sim = sim
        self.error = ""
        self._lock = threading.RLock()
        self.hw = None
        self._open()
        self.mode = "stopped"          # stopped | move | continuous | auto
        self.auto_leg = 0
        self.auto_cycles = 0
        self.mount_position = 0
        self.mount_referenced = False
        self.mount_requested = 0
        self._stop = threading.Event()
        self._thread = threading.Thread(target=self._loop, daemon=True, name="motors")
        self._thread.start()

    # ---------------------------------------------------------------- backend
    def _open(self):
        if self.hw is not None:
            self.hw.close()
        self.hw = None
        if not self.sim and self.s.motor_driver in ("hat", "c"):
            try:
                self.hw = LgpioBackend()
                self.error = ""
            except Exception as e:
                self.error = str(e)
                self.log("WARN", f"Motors: {e} - panel runs simulated")
        if self.hw is None:
            self.hw = SimBackend()
        self.belt = Channel(self.hw, MOTOR_PINS["conveyor"])
        self.mount = Channel(self.hw, MOTOR_PINS["mount"])

    def set_driver(self, kind: str):
        with self._lock:
            self.stop_all(quiet=True)
            self.s.motor_driver = kind
            self._open()

    def _half(self):
        return half_period_us(c_speed(self.s.conveyor_speed_pct))

    # ------------------------------------------------------------- conveyor
    def run(self, direction=1):
        """Run continuously (Run with the line, Run belt)."""
        with self._lock:
            self.belt.start(direction, self._half(), 0)
            self.mode = "continuous"
        self.log("INFO", f"Conveyor running {'forward' if direction > 0 else 'reverse'} "
                         f"at {self.s.conveyor_speed_pct} %")

    def move(self, direction, steps):
        """Forward / Reverse buttons of the motor program: a set number of steps."""
        with self._lock:
            self.belt.start(direction, self._half(), max(1, min(MAX_STEPS, int(steps))))
            self.mode = "move"

    def auto(self, steps):
        """Back and forth: forward `steps`, reverse `steps`, repeat."""
        with self._lock:
            self.auto_leg = max(1, min(MAX_STEPS, int(steps)))
            self.auto_cycles = 0
            self.belt.start(1, self._half(), self.auto_leg)
            self.mode = "auto"

    def stop(self, quiet=False):
        with self._lock:
            was = self.belt.running
            self.belt.stop()
            self.mode = "stopped"
        if was and not quiet:
            self.log("INFO", "Conveyor stopped")

    def set_speed(self, pct: int):
        with self._lock:
            self.s.conveyor_speed_pct = pct
            self.belt.change_speed(self._half())

    # ---------------------------------------------------------------- mount
    def _mount_go(self, delta):
        if delta == 0:
            return
        self.mount_requested = min(MAX_STEPS, abs(delta))
        self.mount.start(1 if delta > 0 else -1, half_period_us(MOUNT_SPEED), self.mount_requested)

    def _mount_settle(self):
        """Add the steps of the current / stopped camera move to the position."""
        if self.mount.running:
            self.mount_position += self.mount.dir * self.mount.stop()

    def mount_move(self, direction, steps):
        with self._lock:
            self._mount_settle()
            self._mount_go((1 if direction > 0 else -1) * max(1, min(MAX_STEPS, int(steps))))

    def mount_goto(self, position) -> bool:
        with self._lock:
            if not self.mount_referenced or not 0 <= position <= MOUNT_MAX_POS:
                return False
            self._mount_settle()
            self._mount_go(position - self.mount_position)
            return True

    def mount_set_reference(self) -> bool:
        with self._lock:
            if self.mount.running:
                return False
            self.mount_position, self.mount_referenced = 0, True
        self.log("INFO", "Camera height: 12 oz reference set (position 0)")
        return True

    def mount_stop(self):
        with self._lock:
            self._mount_settle()

    # ------------------------------------------------------------------ all
    def stop_all(self, quiet=False):
        self.stop(quiet=quiet)
        self.mount_stop()

    def halt(self):
        """E-stop."""
        self.stop_all(quiet=True)

    def _loop(self):
        while not self._stop.wait(self.TICK):
            with self._lock:
                if self.belt.finished():
                    if self.mode == "auto":
                        if self.belt.dir < 0:
                            self.auto_cycles += 1
                        self.belt.start(-self.belt.dir, self.belt.half_us, self.auto_leg)
                    else:
                        self.belt.stop()
                        self.mode = "stopped"
                if self.mount.finished():
                    self.mount_position += self.mount.dir * self.mount.requested
                    self.mount.stop()

    # --------------------------------------------------------------- status
    def status(self) -> dict:
        with self._lock:
            b, m = self.belt, self.mount
            sp = c_speed(self.s.conveyor_speed_pct)
            mpos = self.mount_position + (m.dir * m.steps_done() if m.running else 0)
            return {
                "running": b.running, "mode": self.mode, "dir": b.dir,
                "speed_pct": self.s.conveyor_speed_pct,
                "steps_per_s": round(1e6 / (2 * half_period_us(sp))),
                "mm_per_step": self.s.conveyor_mm_per_step,
                "steps_done": b.steps_done(), "steps_requested": b.requested or self.auto_leg,
                "auto_cycles": self.auto_cycles,
                "move_steps": self.s.conveyor_move_steps,
                "with_line": self.s.conveyor_with_line,
                "mount_running": m.running, "mount_dir": m.dir,
                "mount_position": mpos if self.mount_referenced else None,
                "mount_steps_done": m.steps_done(), "mount_requested": self.mount_requested,
                "mount_move_steps": self.s.mount_move_steps,
                "presets": MOUNT_PRESETS, "mount_fitted": self.s.mount_motor,
                "driver": self.s.motor_driver, "driver_name": self.hw.name, "error": self.error,
                "can_mm": self.s.can_diameter_mm,
            }

    def close(self):
        try:
            self.stop_all(quiet=True)
        except Exception as e:
            self.log("ERROR", f"Motors: stop failed at shutdown ({e})")
        self._stop.set()
        self._thread.join(timeout=0.5)
        self.hw.close()


# =============================================================================
# The team's C motor program (motor_c/motord) - same code as ./motor
# =============================================================================
MOTOR_C_DIR = Path(__file__).resolve().parent.parent / "motor_c"


class CMotors:
    """Runs motor_c/motord: motor_control.c + HR8825.c + DEV_Config.c from the team's
    GTK program, unchanged, so steps, speeds and timing are exactly the same.
    The station sends it the same calls the GTK buttons made."""

    def __init__(self, settings, log):
        self.s, self.log = settings, log
        self.error = ""
        self._lock = threading.Lock()
        self._cache, self._cache_t = None, 0.0
        exe = MOTOR_C_DIR / "motord"
        if not exe.exists() or any(f.stat().st_mtime > exe.stat().st_mtime
                                   for f in MOTOR_C_DIR.glob("*.[ch]")):
            self._build()
        self.p = subprocess.Popen([str(exe)], stdin=subprocess.PIPE, stdout=subprocess.PIPE,
                                  stderr=subprocess.STDOUT, text=True, bufsize=1, cwd=MOTOR_C_DIR)
        hello = self.p.stdout.readline().strip()
        if not hello.startswith("OK"):
            self.p.kill()
            raise RuntimeError(hello or "motord did not start")
        self.hardware = "hardware=1" in hello
        self.name = "team C driver" if self.hardware else "team C driver (sim build)"

    def _build(self):
        if not shutil.which("make") or not shutil.which("gcc"):
            raise RuntimeError("motor_c/motord not built and no compiler - sudo apt install build-essential "
                               "libglib2.0-dev liblgpio-dev, then: make -C motor_c")
        r = subprocess.run(["make", "-C", str(MOTOR_C_DIR)], capture_output=True, text=True)
        if r.returncode:
            tail = (r.stderr or r.stdout).strip().splitlines()[-3:]
            raise RuntimeError("building motor_c failed: " + " | ".join(tail) +
                               " (sudo apt install build-essential libglib2.0-dev liblgpio-dev)")
        self.log("INFO", "Motors: built motor_c/motord from the team motor code")

    def cmd(self, line: str) -> str:
        with self._lock:
            if self.p.poll() is not None:
                raise RuntimeError("motor program stopped - restart the station")
            self.p.stdin.write(line + "\n")
            self.p.stdin.flush()
            reply = self.p.stdout.readline().strip()
            self._cache = None
        if reply.startswith("ERR"):
            raise ValueError(reply[4:])
        return reply

    def status(self):
        now = time.monotonic()
        if self._cache is None or now - self._cache_t > 0.08:
            with self._lock:
                self.p.stdin.write("status\n")
                self.p.stdin.flush()
                f = self.p.stdout.readline().split()
            v = [int(x) for x in f[1:]]
            keys = ["running", "osc", "cont", "dir", "speed", "done", "req", "leg_done", "osc_steps",
                    "m_running", "m_dir", "m_done", "m_req", "m_pos", "cycles", "hw"]
            self._cache, self._cache_t = dict(zip(keys, v)), now
        return self._cache

    def close(self):
        try:
            self.cmd("stopall")
            self.p.stdin.write("quit\n")
            self.p.stdin.flush()
            self.p.wait(timeout=2)
        except Exception:
            self.p.kill()


class Conveyor:
    """What the dashboard uses. motor_driver: "c" = the team's C code (default),
    "hat" = Python port, "off" = simulated."""

    def __init__(self, settings, log, sim=False):
        self.s, self.log, self.sim = settings, log, sim
        self.c = None
        self.py = None
        self.error = ""
        self._open()

    def _open(self):
        if self.c:
            self.c.close()
        if self.py:
            self.py.close()
        self.c = self.py = None
        self.error = ""
        if self.s.motor_driver == "c" and not self.sim:
            try:
                self.c = CMotors(self.s, self.log)
                return
            except Exception as e:
                self.error = f"team C driver: {e}"
                self.log("WARN", f"Motors: {e} - panel runs simulated")
        drv = self.s.motor_driver
        if self.s.motor_driver == "c":
            self.s.motor_driver = "off"                  # simulate, but don't save that choice
        self.py = PyMotors(self.s, self.log, sim=self.sim)
        self.s.motor_driver = drv
        if self.error:
            self.py.error = self.error

    def set_driver(self, kind):
        self.s.motor_driver = kind
        self._open()

    # --------------------------------------------------- commands (as main.c)
    def _speed(self):
        return c_speed(self.s.conveyor_speed_pct)

    def run(self, direction=1):
        if self.c:
            self.c.cmd(f"run {1 if direction > 0 else -1} {self._speed()}")
            self.log("INFO", f"Conveyor running at {self.s.conveyor_speed_pct} %")
        else:
            self.py.run(direction)

    def move(self, direction, steps):
        if self.c:
            self.c.cmd(f"move {1 if direction > 0 else -1} {self._speed()} {int(steps)}")
        else:
            self.py.move(direction, steps)

    def auto(self, steps):
        if self.c:
            self.c.cmd(f"auto {self._speed()} {int(steps)}")
        else:
            self.py.auto(steps)

    def stop(self, quiet=False):
        if self.c:
            was = self.c.status()["running"]
            self.c.cmd("stop")
            if was and not quiet:
                self.log("INFO", "Conveyor stopped")
        else:
            self.py.stop(quiet)

    def set_speed(self, pct):
        self.s.conveyor_speed_pct = pct
        if self.c:
            st = self.c.status()
            self.c.cmd(f"speed {st['dir'] or 1} {self._speed()}")      # motor_conveyor_settings
        else:
            self.py.set_speed(pct)

    def mount_move(self, direction, steps):
        if self.c:
            self.c.cmd(f"mount {1 if direction > 0 else -1} {int(steps)}")
        else:
            self.py.mount_move(direction, steps)

    def mount_goto(self, position):
        if self.c:
            try:
                self.c.cmd(f"goto {int(position)}")
                return True
            except ValueError:
                return False
        return self.py.mount_goto(position)

    def mount_set_reference(self):
        if self.c:
            if self.c.status()["m_running"]:
                return False
            self.c.cmd("ref")
            self.log("INFO", "Camera height: 12 oz reference set (position 0)")
            return True
        return self.py.mount_set_reference()

    def mount_stop(self):
        self.c.cmd("mstop") if self.c else self.py.mount_stop()

    def stop_all(self, quiet=False):
        self.c.cmd("stopall") if self.c else self.py.stop_all(quiet)

    def halt(self):
        self.stop_all(quiet=True)

    def status(self):
        if not self.c:
            st = self.py.status()
            st["driver"] = self.s.motor_driver
            return st
        try:
            v = self.c.status()
        except Exception as e:                       # motord died - fall back so the dashboard keeps running
            self.log("ERROR", f"Motors: team C driver stopped ({e}) - panel now simulated, restart the station")
            try:
                self.c.p.kill()
            except Exception:
                pass
            self.c = None
            self.error = f"team C driver stopped: {e}"
            drv, self.s.motor_driver = self.s.motor_driver, "off"
            self.py = PyMotors(self.s, self.log, sim=True)
            self.s.motor_driver = drv
            self.py.error = self.error
            return self.status()
        osc, run = v["osc"], v["running"]
        mode = "stopped" if not run else "auto" if osc else "continuous" if v["cont"] else "move"
        return {
            "running": bool(run), "mode": mode, "dir": v["dir"],
            "speed_pct": self.s.conveyor_speed_pct,
            "steps_per_s": round(1e6 / (2 * half_period_us(c_speed(self.s.conveyor_speed_pct)))),
            "mm_per_step": self.s.conveyor_mm_per_step,
            "steps_done": v["leg_done"] if osc else v["done"],
            "steps_requested": v["osc_steps"] if osc else v["req"],
            "auto_cycles": v["cycles"],
            "move_steps": self.s.conveyor_move_steps, "with_line": self.s.conveyor_with_line,
            "mount_running": bool(v["m_running"]), "mount_dir": v["m_dir"],
            "mount_position": None if v["m_pos"] == -999999 else v["m_pos"],
            "mount_steps_done": v["m_done"], "mount_requested": v["m_req"],
            "mount_move_steps": self.s.mount_move_steps,
            "presets": MOUNT_PRESETS, "mount_fitted": self.s.mount_motor,
            "driver": "c", "driver_name": self.c.name, "error": "",
            "can_mm": self.s.can_diameter_mm, "max_steps": MAX_STEPS,
        }

    def close(self):
        if self.c:
            self.c.close()
        if self.py:
            self.py.close()
