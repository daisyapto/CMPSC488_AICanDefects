"""
Conveyor belt + camera height motors - the team's Waveshare Stepper Motor HAT (B)
(two HR8825 / DRV8825 drivers), ported from motor_control.c / HR8825.c /
DEV_Config.h so the dashboard does what the GTK motor program does.

    MOTOR1 = conveyor belt        EN 12 · DIR 13 · STEP 19 · M0 16 · M1 17 · M2 20
    MOTOR2 = camera up/down mount EN 4  · DIR 24 · STEP 18 · M0 21 · M1 22 · M2 27

Same behaviour as the C program:
  * EN HIGH = driver on (the HAT inverts it); the driver is switched off when idle.
  * DIR LOW = forward / up, HIGH = reverse / down.
  * Microstepping comes from the HAT's DIP switches (M0-M2 held LOW, "HARDWARD").
  * Conveyor speed slider 0-100 % -> C speed 53..83 -> half period 1100 - 10*speed us
    (570..270 us = 877..1852 steps/s). Camera moves at fixed speed 60 (500 us).
  * Camera presets from the 12 oz reference: 12 oz = 0, 16 oz = 3300, 19.2 oz = 6600 steps.

Step pulses are generated by lgpio's pulse thread (tx_pulse with a cycle count),
not by Python sleeps, so the dashboard and camera can't disturb the timing.

Only one program may drive these pins - close the GTK motor program first.
NEVER plug or unplug a motor cable while the HAT has power.
"""
from __future__ import annotations

import threading
import time

from .config import MOTOR_PINS

MAX_STEPS = 9000                        # per command, as in motor_control.c
MOUNT_SPEED = 60
MOUNT_PRESETS = {"12 oz": 0, "16 oz": 3300, "19.2 oz": 6600}
MOUNT_MAX_POS = 6600


def c_speed(pct: float) -> int:
    """Slider % -> motor_control.c speed (53..83), same rounding as main.c."""
    return 53 + int(max(0.0, min(100.0, pct)) * 30.0 / 100.0 + 0.5)


def half_period_us(speed: int) -> int:
    return 1100 - speed * 10


# =============================================================================
# GPIO backends
# =============================================================================
class LgpioBackend:
    name = "Motor HAT"

    def __init__(self):
        import lgpio
        self.lg = lgpio
        self.h = None
        err = None
        for chip in (0, 4):                    # Pi 5: header = gpiochip0 (gpiochip4 on old kernels)
            try:
                h = lgpio.gpiochip_open(chip)
                if h >= 0:
                    self.h = h
                    break
            except Exception as e:
                err = e
        if self.h is None:
            raise RuntimeError(f"cannot open the GPIO chip ({err})")
        for motor in MOTOR_PINS.values():
            for pin in motor.values():
                try:
                    lgpio.gpio_claim_output(self.h, pin, 0)
                except Exception as e:
                    raise RuntimeError(f"GPIO {pin} is busy ({e}) - is the GTK motor program running? Close it")

    def write(self, pin, level):
        self.lg.gpio_write(self.h, pin, 1 if level else 0)

    def pulses(self, pin, half_us, cycles):
        """cycles step pulses (0 = endless). Replaces whatever is running on that pin."""
        self.lg.tx_pulse(self.h, pin, 0, 0)                     # stop + clear the queue
        if half_us:
            self.lg.tx_pulse(self.h, pin, half_us, half_us, 0, cycles)

    def busy(self, pin) -> bool:
        return bool(self.lg.tx_busy(self.h, pin, self.lg.TX_PWM))

    def close(self):
        try:
            for motor in MOTOR_PINS.values():
                self.lg.tx_pulse(self.h, motor["step"], 0, 0)
                self.write(motor["en"], 0)
            for motor in MOTOR_PINS.values():
                for pin in motor.values():
                    self.lg.gpio_free(self.h, pin)
            self.lg.gpiochip_close(self.h)
        except Exception:
            pass


class SimBackend:
    """No hardware: pulse trains are timed so the panel behaves like the real thing."""
    name = "simulated"

    def __init__(self):
        self._end = {}

    def write(self, pin, level):
        pass

    def pulses(self, pin, half_us, cycles):
        self._end[pin] = None if not half_us else (
            float("inf") if cycles == 0 else time.monotonic() + cycles * 2 * half_us / 1e6)

    def busy(self, pin) -> bool:
        end = self._end.get(pin)
        return end is not None and time.monotonic() < end

    def close(self):
        pass


# =============================================================================
# One motor channel
# =============================================================================
class Channel:
    def __init__(self, hw, pins):
        self.hw, self.p = hw, pins
        self.running = False
        self.dir = 1
        self.half_us = 0
        self.requested = 0            # steps in this command (0 = endless)
        self._t0 = 0.0
        self._done_before = 0         # steps already done before a speed change

    def steps_done(self) -> int:
        if not self.running:
            return 0
        n = self._done_before + int((time.monotonic() - self._t0) * 1e6 / (2 * self.half_us))
        return min(n, self.requested) if self.requested else n

    def start(self, direction, half_us, steps):
        hw = self.hw
        hw.pulses(self.p["step"], 0, 0)
        hw.write(self.p["en"], 1)                     # HR8825_Enable
        hw.write(self.p["dir"], 0 if direction > 0 else 1)
        time.sleep(0.0005)                            # DIR set-up before the first step
        self.dir, self.half_us, self.requested = (1 if direction > 0 else -1), half_us, steps
        self._t0, self._done_before = time.monotonic(), 0
        self.running = True
        hw.pulses(self.p["step"], half_us, steps)

    def change_speed(self, half_us):
        if not self.running or half_us == self.half_us:
            self.half_us = half_us
            return
        done = self.steps_done()
        left = (self.requested - done) if self.requested else 0
        if self.requested and left <= 0:
            return
        self._done_before, self._t0, self.half_us = done, time.monotonic(), half_us
        self.hw.pulses(self.p["step"], half_us, left)

    def stop(self) -> int:
        """Stop now; returns the steps that were done."""
        done = self.steps_done()
        self.hw.pulses(self.p["step"], 0, 0)
        self.hw.write(self.p["en"], 0)                # HR8825_Stop
        self.running = False
        return done

    def finished(self) -> bool:
        return self.running and self.requested > 0 and not self.hw.busy(self.p["step"])


# =============================================================================
# Conveyor + camera mount
# =============================================================================
class Conveyor:
    TICK = 0.02

    def __init__(self, settings, log, sim=False):
        self.s = settings
        self.log = log
        self.sim = sim
        self.error = ""
        self._lock = threading.RLock()
        self.hw = None
        self._open()
        self.mode = "stopped"          # stopped | move | continuous | auto
        self.auto_leg = 0
        self.auto_cycles = 0
        self.mount_position = 0
        self.mount_referenced = False
        self.mount_requested = 0
        self._stop = threading.Event()
        self._thread = threading.Thread(target=self._loop, daemon=True, name="motors")
        self._thread.start()

    # ---------------------------------------------------------------- backend
    def _open(self):
        if self.hw is not None:
            self.hw.close()
        self.hw = None
        if not self.sim and self.s.motor_driver == "hat":
            try:
                self.hw = LgpioBackend()
                self.error = ""
            except Exception as e:
                self.error = str(e)
                self.log("WARN", f"Motors: {e} - panel runs simulated")
        if self.hw is None:
            self.hw = SimBackend()
        self.belt = Channel(self.hw, MOTOR_PINS["conveyor"])
        self.mount = Channel(self.hw, MOTOR_PINS["mount"])

    def set_driver(self, kind: str):
        with self._lock:
            self.stop_all(quiet=True)
            self.s.motor_driver = kind
            self._open()

    def _half(self):
        return half_period_us(c_speed(self.s.conveyor_speed_pct))

    # ------------------------------------------------------------- conveyor
    def run(self, direction=1):
        """Run continuously (Run with the line, Run belt)."""
        with self._lock:
            self.belt.start(direction, self._half(), 0)
            self.mode = "continuous"
        self.log("INFO", f"Conveyor running {'forward' if direction > 0 else 'reverse'} "
                         f"at {self.s.conveyor_speed_pct} %")

    def move(self, direction, steps):
        """Forward / Reverse buttons of the motor program: a set number of steps."""
        with self._lock:
            self.belt.start(direction, self._half(), max(1, min(MAX_STEPS, int(steps))))
            self.mode = "move"

    def auto(self, steps):
        """Back and forth: forward `steps`, reverse `steps`, repeat."""
        with self._lock:
            self.auto_leg = max(1, min(MAX_STEPS, int(steps)))
            self.auto_cycles = 0
            self.belt.start(1, self._half(), self.auto_leg)
            self.mode = "auto"

    def stop(self, quiet=False):
        with self._lock:
            was = self.belt.running
            self.belt.stop()
            self.mode = "stopped"
        if was and not quiet:
            self.log("INFO", "Conveyor stopped")

    def set_speed(self, pct: int):
        with self._lock:
            self.s.conveyor_speed_pct = pct
            self.belt.change_speed(self._half())

    # ---------------------------------------------------------------- mount
    def _mount_go(self, delta):
        if delta == 0:
            return
        self.mount_requested = min(MAX_STEPS, abs(delta))
        self.mount.start(1 if delta > 0 else -1, half_period_us(MOUNT_SPEED), self.mount_requested)

    def _mount_settle(self):
        """Add the steps of the current / stopped camera move to the position."""
        if self.mount.running:
            self.mount_position += self.mount.dir * self.mount.stop()

    def mount_move(self, direction, steps):
        with self._lock:
            self._mount_settle()
            self._mount_go((1 if direction > 0 else -1) * max(1, min(MAX_STEPS, int(steps))))

    def mount_goto(self, position) -> bool:
        with self._lock:
            if not self.mount_referenced or not 0 <= position <= MOUNT_MAX_POS:
                return False
            self._mount_settle()
            self._mount_go(position - self.mount_position)
            return True

    def mount_set_reference(self) -> bool:
        with self._lock:
            if self.mount.running:
                return False
            self.mount_position, self.mount_referenced = 0, True
        self.log("INFO", "Camera height: 12 oz reference set (position 0)")
        return True

    def mount_stop(self):
        with self._lock:
            self._mount_settle()

    # ------------------------------------------------------------------ all
    def stop_all(self, quiet=False):
        self.stop(quiet=quiet)
        self.mount_stop()

    def halt(self):
        """E-stop."""
        self.stop_all(quiet=True)

    def _loop(self):
        while not self._stop.wait(self.TICK):
            with self._lock:
                if self.belt.finished():
                    if self.mode == "auto":
                        if self.belt.dir < 0:
                            self.auto_cycles += 1
                        self.belt.start(-self.belt.dir, self.belt.half_us, self.auto_leg)
                    else:
                        self.belt.stop()
                        self.mode = "stopped"
                if self.mount.finished():
                    self.mount_position += self.mount.dir * self.mount.requested
                    self.mount.stop()

    # --------------------------------------------------------------- status
    def status(self) -> dict:
        with self._lock:
            b, m = self.belt, self.mount
            sp = c_speed(self.s.conveyor_speed_pct)
            mpos = self.mount_position + (m.dir * m.steps_done() if m.running else 0)
            return {
                "running": b.running, "mode": self.mode, "dir": b.dir,
                "speed_pct": self.s.conveyor_speed_pct,
                "steps_per_s": round(1e6 / (2 * half_period_us(sp))),
                "mm_per_step": self.s.conveyor_mm_per_step,
                "steps_done": b.steps_done(), "steps_requested": b.requested or self.auto_leg,
                "auto_cycles": self.auto_cycles,
                "move_steps": self.s.conveyor_move_steps,
                "with_line": self.s.conveyor_with_line,
                "mount_running": m.running, "mount_dir": m.dir,
                "mount_position": mpos if self.mount_referenced else None,
                "mount_steps_done": m.steps_done(), "mount_requested": self.mount_requested,
                "mount_move_steps": self.s.mount_move_steps,
                "presets": MOUNT_PRESETS,
                "driver": self.s.motor_driver, "driver_name": self.hw.name, "error": self.error,
                "can_mm": self.s.can_diameter_mm,
            }

    def close(self):
        self.stop_all(quiet=True)
        self._stop.set()
        self._thread.join(timeout=0.5)
        self.hw.close()
